export function getPostDatasetVersionRecordsKey() {
  return [':dataset', '/:dataset/:version/records', 'POST'] as const
}

export function usePostDatasetVersionRecords<TError = unknown>(options?: {
  mutation?: SWRMutationConfiguration<
    Awaited<
      ReturnType<
        typeof parseResponse<
          Awaited<ReturnType<(typeof client)[':dataset'][':version']['records']['$post']>>
        >
      >
    >,
    TError,
    Key,
    InferRequestType<(typeof client)[':dataset'][':version']['records']['$post']>
  > & { swrKey?: Key; throwOnError?: boolean }
  options?: ClientRequestOptions
}) {
  const { mutation: mutationOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, ...restMutationOptions } = mutationOptions ?? {}
  const swrKey = customKey ?? getPostDatasetVersionRecordsKey()
  return {
    swrKey,
    ...useSWRMutation(
      swrKey,
      async (
        _: Key,
        {
          arg,
        }: { arg: InferRequestType<(typeof client)[':dataset'][':version']['records']['$post']> },
      ) => parseResponse(client[':dataset'][':version'].records.$post(arg, clientOptions)),
      restMutationOptions,
    ),
  }
}
