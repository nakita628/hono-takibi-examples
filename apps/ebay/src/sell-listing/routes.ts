export const postItemDraftIndexRoute = createRoute({
  method: 'post',
  path: '/item_draft/',
  tags: ['item_draft'],
  description:
    'This call gives Partners the ability to create an eBay draft of a item for their seller using information from their site. This lets the Partner increase the exposure of items on their site and leverage the eBay user listing experience seamlessly. This experience provides guidance on pricing, aspects, etc. and recommendations that help create a listing that is complete and improves the exposure of the listing in search results. After the listing draft is created, the seller logs into their eBay account and uses the listing experience to finish the listing and publish the item on eBay.',
  operationId: 'createItemDraft',
  request: {
    headers: z.object({
      'Content-Language': z
        .string()
        .exactOptional()
        .openapi({
          param: {
            description:
              'Use this header to specify the natural language of the seller. For details, see Content-Language in HTTP request headers. Required: For EBAY_CA in French. (Content-Language = fr-CA)',
            in: 'header',
            name: 'Content-Language',
            required: false,
            schema: { type: 'string' },
          },
        }),
      'X-EBAY-C-MARKETPLACE-ID': z
        .string()
        .openapi({
          param: {
            description:
              'Use this header to specify an eBay marketplace ID. For a list of supported sites, see API Restrictions in the Listing API overview.',
            in: 'header',
            name: 'X-EBAY-C-MARKETPLACE-ID',
            required: true,
            schema: { type: 'string' },
          },
        }),
    }),
    body: { content: { 'application/json': { schema: ItemDraftSchema } } },
  },
  responses: {
    201: {
      description: 'OK',
      content: { 'application/json': { schema: ItemDraftResponseSchema } },
    },
    400: { description: 'Bad Request' },
    500: { description: 'Internal Server Error' },
  },
  security: [{ api_auth: ['https://api.ebay.com/oauth/api_scope/sell.item.draft'] }],
})
