export function getPostV1NameExecuteCommandKey() {
  return ['v1', '/v1/:name:executeCommand', 'POST'] as const
}

export function usePostV1NameExecuteCommand<TError = unknown>(options?: {
  mutation?: SWRMutationConfiguration<
    Awaited<
      ReturnType<
        typeof parseResponse<
          Awaited<ReturnType<(typeof client.v1)[':name:executeCommand']['$post']>>
        >
      >
    >,
    TError,
    Key,
    InferRequestType<(typeof client.v1)[':name:executeCommand']['$post']>
  > & { swrKey?: Key; throwOnError?: boolean }
  options?: ClientRequestOptions
}) {
  const { mutation: mutationOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, ...restMutationOptions } = mutationOptions ?? {}
  const swrKey = customKey ?? getPostV1NameExecuteCommandKey()
  return {
    swrKey,
    ...useSWRMutation(
      swrKey,
      async (
        _: Key,
        { arg }: { arg: InferRequestType<(typeof client.v1)[':name:executeCommand']['$post']> },
      ) => parseResponse(client.v1[':name:executeCommand'].$post(arg, clientOptions)),
      restMutationOptions,
    ),
  }
}

