export function getPostV1beta1EnvironmentCheckUpgradeKey() {
  return ['v1beta1', '/v1beta1/:environment:checkUpgrade', 'POST'] as const
}

export function usePostV1beta1EnvironmentCheckUpgrade<TError = unknown>(options?: {
  mutation?: SWRMutationConfiguration<
    Awaited<
      ReturnType<
        typeof parseResponse<
          Awaited<ReturnType<(typeof client.v1beta1)[':environment:checkUpgrade']['$post']>>
        >
      >
    >,
    TError,
    Key,
    InferRequestType<(typeof client.v1beta1)[':environment:checkUpgrade']['$post']>
  > & { swrKey?: Key; throwOnError?: boolean }
  options?: ClientRequestOptions
}) {
  const { mutation: mutationOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, ...restMutationOptions } = mutationOptions ?? {}
  const swrKey = customKey ?? getPostV1beta1EnvironmentCheckUpgradeKey()
  return {
    swrKey,
    ...useSWRMutation(
      swrKey,
      async (
        _: Key,
        {
          arg,
        }: { arg: InferRequestType<(typeof client.v1beta1)[':environment:checkUpgrade']['$post']> },
      ) => parseResponse(client.v1beta1[':environment:checkUpgrade'].$post(arg, clientOptions)),
      restMutationOptions,
    ),
  }
}

