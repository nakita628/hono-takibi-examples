export function getGetV1betaAccessPoliciesKey(
  args: InferRequestType<typeof client.v1beta.accessPolicies.$get>,
) {
  return ['v1beta', '/v1beta/accessPolicies', args] as const
}

export function useGetV1betaAccessPolicies<TError = unknown>(
  args: InferRequestType<typeof client.v1beta.accessPolicies.$get>,
  options?: {
    swr?: SWRConfiguration<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<typeof client.v1beta.accessPolicies.$get>>>
        >
      >,
      TError
    > & { swrKey?: Key; enabled?: boolean }
    options?: ClientRequestOptions
  },
) {
  const { swr: swrOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, enabled, ...restSwrOptions } = swrOptions ?? {}
  const swrKey =
    enabled !== false
      ? customKey === undefined
        ? getGetV1betaAccessPoliciesKey(args)
        : customKey
      : null
  return {
    swrKey,
    ...useSWR<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<typeof client.v1beta.accessPolicies.$get>>>
        >
      >,
      TError
    >(
      swrKey,
      async () => parseResponse(client.v1beta.accessPolicies.$get(args, clientOptions)),
      restSwrOptions,
    ),
  }
}

