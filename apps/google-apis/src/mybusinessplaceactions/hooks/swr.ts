export function useGetV1PlaceActionTypeMetadata<TError = unknown>(
  args: InferRequestType<typeof client.v1.placeActionTypeMetadata.$get>,
  options?: {
    swr?: SWRConfiguration<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<typeof client.v1.placeActionTypeMetadata.$get>>>
        >
      >,
      TError
    > & { swrKey?: Key; enabled?: boolean }
    options?: ClientRequestOptions
  },
) {
  const { swr: swrOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, enabled, ...restSwrOptions } = swrOptions ?? {}
  const swrKey =
    enabled !== false
      ? customKey === undefined
        ? getGetV1PlaceActionTypeMetadataKey(args)
        : customKey
      : null
  return {
    swrKey,
    ...useSWR<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<typeof client.v1.placeActionTypeMetadata.$get>>>
        >
      >,
      TError
    >(
      swrKey,
      async () => parseResponse(client.v1.placeActionTypeMetadata.$get(args, clientOptions)),
      restSwrOptions,
    ),
  }
}

