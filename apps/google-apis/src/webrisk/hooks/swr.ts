export function getV1Key() {
  return ['v1'] as const
}

export function getGetV1HashesSearchKey(
  args: InferRequestType<(typeof client.v1)['hashes:search']['$get']>,
) {
  return ['v1', '/v1/hashes:search', args] as const
}

export function useGetV1HashesSearch<TError = unknown>(
  args: InferRequestType<(typeof client.v1)['hashes:search']['$get']>,
  options?: {
    swr?: SWRConfiguration<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<(typeof client.v1)['hashes:search']['$get']>>>
        >
      >,
      TError
    > & { swrKey?: Key; enabled?: boolean }
    options?: ClientRequestOptions
  },
) {
  const { swr: swrOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, enabled, ...restSwrOptions } = swrOptions ?? {}
  const swrKey =
    enabled !== false ? (customKey === undefined ? getGetV1HashesSearchKey(args) : customKey) : null
  return {
    swrKey,
    ...useSWR<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<(typeof client.v1)['hashes:search']['$get']>>>
        >
      >,
      TError
    >(
      swrKey,
      async () => parseResponse(client.v1['hashes:search'].$get(args, clientOptions)),
      restSwrOptions,
    ),
  }
}

