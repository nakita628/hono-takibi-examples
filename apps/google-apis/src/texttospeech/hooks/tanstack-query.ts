export function getV1beta1Key() {
  return ['v1beta1'] as const
}

export function getPostV1beta1TextSynthesizeMutationKey() {
  return ['v1beta1', '/v1beta1/text:synthesize', 'POST'] as const
}

export function getPostV1beta1TextSynthesizeMutationOptions<
  TError = DefaultError,
  TOnMutateResult = unknown,
>(options?: ClientRequestOptions) {
  return mutationOptions<
    Awaited<
      ReturnType<
        typeof parseResponse<
          Awaited<ReturnType<(typeof client.v1beta1)['text:synthesize']['$post']>>
        >
      >
    >,
    TError,
    InferRequestType<(typeof client.v1beta1)['text:synthesize']['$post']>,
    TOnMutateResult
  >({
    mutationKey: getPostV1beta1TextSynthesizeMutationKey(),
    async mutationFn(args: InferRequestType<(typeof client.v1beta1)['text:synthesize']['$post']>) {
      return parseResponse(client.v1beta1['text:synthesize'].$post(args, options))
    },
  })
}

export function usePostV1beta1TextSynthesize<TError = DefaultError, TOnMutateResult = unknown>(
  options?: {
    mutation?: Omit<
      UseMutationOptions<
        Awaited<
          ReturnType<
            typeof parseResponse<
              Awaited<ReturnType<(typeof client.v1beta1)['text:synthesize']['$post']>>
            >
          >
        >,
        TError,
        InferRequestType<(typeof client.v1beta1)['text:synthesize']['$post']>,
        TOnMutateResult
      >,
      'mutationFn'
    >
    options?: ClientRequestOptions
  },
  queryClient?: QueryClient,
) {
  const { mutation: mutationOptions, options: clientOptions } = options ?? {}
  const mutationDefaults = getPostV1beta1TextSynthesizeMutationOptions<TError, TOnMutateResult>(
    clientOptions,
  )
  return useMutation(
    {
      ...mutationOptions,
      ...mutationDefaults,
      mutationKey: mutationOptions?.mutationKey ?? mutationDefaults.mutationKey,
    },
    queryClient,
  )
}

