import { client } from '../client'

export function getV1Key() {
  return ['v1'] as const
}

export function getPostV1EnvironmentAddPublicKeyMutationKey() {
  return ['v1', '/v1/:environment:addPublicKey', 'POST'] as const
}

export function getPostV1EnvironmentAddPublicKeyMutationOptions<
  TError = DefaultError,
  TOnMutateResult = unknown,
>(options?: ClientRequestOptions) {
  return mutationOptions<
    Awaited<
      ReturnType<
        typeof parseResponse<
          Awaited<ReturnType<(typeof client.v1)[':environment:addPublicKey']['$post']>>
        >
      >
    >,
    TError,
    InferRequestType<(typeof client.v1)[':environment:addPublicKey']['$post']>,
    TOnMutateResult
  >({
    mutationKey: getPostV1EnvironmentAddPublicKeyMutationKey(),
    async mutationFn(
      args: InferRequestType<(typeof client.v1)[':environment:addPublicKey']['$post']>,
    ) {
      return parseResponse(client.v1[':environment:addPublicKey'].$post(args, options))
    },
  })
}

export function injectPostV1EnvironmentAddPublicKey<
  TError = DefaultError,
  TOnMutateResult = unknown,
>(
  options?: () => {
    mutation?: Omit<
      CreateMutationOptions<
        Awaited<
          ReturnType<
            typeof parseResponse<
              Awaited<ReturnType<(typeof client.v1)[':environment:addPublicKey']['$post']>>
            >
          >
        >,
        TError,
        InferRequestType<(typeof client.v1)[':environment:addPublicKey']['$post']>,
        TOnMutateResult
      >,
      'mutationFn'
    >
    options?: ClientRequestOptions
  },
  injectOptions?: InjectMutationOptions,
) {
  return injectMutation(() => {
    const { mutation, options: clientOptions } = options?.() ?? {}
    const mutationDefaults = getPostV1EnvironmentAddPublicKeyMutationOptions<
      TError,
      TOnMutateResult
    >(clientOptions)
    return {
      ...mutation,
      ...mutationDefaults,
      mutationKey: mutation?.mutationKey ?? mutationDefaults.mutationKey,
    }
  }, injectOptions)
}

