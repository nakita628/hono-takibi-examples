export const getApisRoute = createRoute({
  method: 'get',
  path: '/apis',
  tags: ['apis'],
  description: 'Retrieve the list of APIs supported at this endpoint.',
  operationId: 'discovery.apis.list',
  request: {
    query: z.object({
      alt: AltParamsSchema,
      fields: FieldsParamsSchema,
      key: KeyParamsSchema,
      oauth_token: OauthTokenParamsSchema,
      prettyPrint: PrettyPrintParamsSchema,
      quotaUser: QuotaUserParamsSchema,
      userIp: UserIpParamsSchema,
      name: z
        .string()
        .exactOptional()
        .openapi({
          param: {
            description: 'Only include APIs with the given name.',
            in: 'query',
            name: 'name',
            schema: { type: 'string' },
            required: false,
          },
        }),
      preferred: z
        .stringbool()
        .exactOptional()
        .openapi({
          param: {
            description: 'Return only the preferred version of an API.',
            in: 'query',
            name: 'preferred',
            schema: { type: 'boolean' },
            required: false,
          },
        }),
    }),
  },
  responses: {
    200: {
      description: 'Successful response',
      content: { 'application/json': { schema: DirectoryListSchema } },
    },
  },
})

