export const postGroupsV1GroupsGroupIdArchiveRoute = createRoute({
  method: 'post',
  path: '/groups/v1/groups/{groupId}/archive',
  tags: ['archive'],
  description: 'Inserts a new mail into the archive of the Google group.',
  operationId: 'groupsmigration.archive.insert',
  request: {
    query: z.object({
      '$.xgafv': XgafvParamsSchema,
      access_token: AccessTokenParamsSchema,
      alt: AltParamsSchema,
      callback: CallbackParamsSchema,
      fields: FieldsParamsSchema,
      key: KeyParamsSchema,
      oauth_token: OauthTokenParamsSchema,
      prettyPrint: PrettyPrintParamsSchema,
      quotaUser: QuotaUserParamsSchema,
      upload_protocol: UploadProtocolParamsSchema,
      uploadType: UploadTypeParamsSchema,
    }),
    params: z.object({
      groupId: z
        .string()
        .openapi({
          param: {
            description: 'The group ID',
            in: 'path',
            name: 'groupId',
            required: true,
            schema: { type: 'string' },
          },
        }),
    }),
  },
  responses: {
    200: {
      description: 'Successful response',
      content: { 'application/json': { schema: GroupsSchema } },
    },
  },
  security: [
    {
      Oauth2: ['https://www.googleapis.com/auth/apps.groups.migration'],
      Oauth2c: ['https://www.googleapis.com/auth/apps.groups.migration'],
    },
  ],
})
