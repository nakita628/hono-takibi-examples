import { client } from '../client'

export function getV2Key() {
  return ['v2'] as const
}

export function getGetV2KeysLookupKeyKey(
  args: InferRequestType<(typeof client.v2)['keys:lookupKey']['$get']>,
) {
  return ['v2', '/v2/keys:lookupKey', args] as const
}

export function useGetV2KeysLookupKey<TError = unknown>(
  args: InferRequestType<(typeof client.v2)['keys:lookupKey']['$get']>,
  options?: {
    swr?: SWRConfiguration<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<(typeof client.v2)['keys:lookupKey']['$get']>>>
        >
      >,
      TError
    > & { swrKey?: Key; enabled?: boolean }
    options?: ClientRequestOptions
  },
) {
  const { swr: swrOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, enabled, ...restSwrOptions } = swrOptions ?? {}
  const swrKey =
    enabled !== false
      ? customKey === undefined
        ? getGetV2KeysLookupKeyKey(args)
        : customKey
      : null
  return {
    swrKey,
    ...useSWR<
      Awaited<
        ReturnType<
          typeof parseResponse<Awaited<ReturnType<(typeof client.v2)['keys:lookupKey']['$get']>>>
        >
      >,
      TError
    >(
      swrKey,
      async () => parseResponse(client.v2['keys:lookupKey'].$get(args, clientOptions)),
      restSwrOptions,
    ),
  }
}

