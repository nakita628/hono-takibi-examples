import useSWR from 'swr'
import useSWRImmutable from 'swr/immutable'
import type { Key, SWRConfiguration } from 'swr'
import useSWRMutation from 'swr/mutation'
import type { SWRMutationConfiguration } from 'swr/mutation'
import type { ClientRequestOptions, InferRequestType } from 'hono/client'
import { parseResponse } from 'hono/client'
import { client } from '../client'

export function getEnvironmentKey() {
  return ['environment'] as const
}

export function getTagsKey() {
  return ['tags'] as const
}

export function getGetEnvironmentKey(args: InferRequestType<typeof client.environment.$get>) {
  const { header: _, ...keyArgs } = args
  return ['environment', '/environment', keyArgs] as const
}

export function useGetEnvironment<TError = unknown>(
  args: InferRequestType<typeof client.environment.$get>,
  options?: {
    swr?: SWRConfiguration<
      Awaited<
        ReturnType<typeof parseResponse<Awaited<ReturnType<typeof client.environment.$get>>>>
      >,
      TError
    > & { swrKey?: Key; enabled?: boolean }
    options?: ClientRequestOptions
  },
) {
  const { swr: swrOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, enabled, ...restSwrOptions } = swrOptions ?? {}
  const swrKey =
    enabled !== false ? (customKey === undefined ? getGetEnvironmentKey(args) : customKey) : null
  return {
    swrKey,
    ...useSWR<
      Awaited<
        ReturnType<typeof parseResponse<Awaited<ReturnType<typeof client.environment.$get>>>>
      >,
      TError
    >(
      swrKey,
      async () => parseResponse(client.environment.$get(args, clientOptions)),
      restSwrOptions,
    ),
  }
}

