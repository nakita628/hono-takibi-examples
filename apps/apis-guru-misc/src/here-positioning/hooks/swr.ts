export function getPostLocateKey() {
  return ['locate', '/locate', 'POST'] as const
}

export function usePostLocate<TError = unknown>(options?: {
  mutation?: SWRMutationConfiguration<
    Awaited<ReturnType<typeof parseResponse<Awaited<ReturnType<typeof client.locate.$post>>>>>,
    TError,
    Key,
    InferRequestType<typeof client.locate.$post>
  > & { swrKey?: Key; throwOnError?: boolean }
  options?: ClientRequestOptions
}) {
  const { mutation: mutationOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, ...restMutationOptions } = mutationOptions ?? {}
  const swrKey = customKey ?? getPostLocateKey()
  return {
    swrKey,
    ...useSWRMutation(
      swrKey,
      async (_: Key, { arg }: { arg: InferRequestType<typeof client.locate.$post> }) =>
        parseResponse(client.locate.$post(arg, clientOptions)),
      restMutationOptions,
    ),
  }
}

