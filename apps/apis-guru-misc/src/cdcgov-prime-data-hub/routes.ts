export const postReportsRoute = createRoute({
  method: 'post',
  path: '/reports',
  summary: 'Post a report to the data hub',
  request: {
    query: z.object({
      client: z
        .string()
        .openapi({
          param: {
            description: "The client's name that matches the client name in metadata",
            example: 'simple_report',
            in: 'query',
            name: 'client',
            required: true,
            schema: { type: 'string' },
          },
        }),
      option: z
        .enum([
          'ValidatePayload',
          'CheckConnections',
          'SendImmediately',
          'SkipSend',
          'SkipInvalidItems',
        ])
        .exactOptional()
        .openapi({
          param: {
            description: 'Optional ways to process the request',
            example: 'ValidatePayload',
            in: 'query',
            name: 'option',
            required: false,
            schema: {
              enum: [
                'ValidatePayload',
                'CheckConnections',
                'SendImmediately',
                'SkipSend',
                'SkipInvalidItems',
              ],
              type: 'string',
            },
          },
        }),
      default: z
        .preprocess(
          (val) =>
            val === undefined
              ? val
              : (Array.isArray(val) ? val : [val]).flatMap((item) =>
                  typeof item === 'string' ? item.split(',') : [item],
                ),
          z.array(z.string()),
        )
        .exactOptional()
        .openapi({
          param: {
            description:
              "Dynamic default values for an element. ':' or %3A is used to seperate element name and value",
            example: 'processing_mode_code%3AD',
            explode: false,
            in: 'query',
            name: 'default',
            required: false,
            schema: { items: { type: 'string' }, type: 'array' },
            style: 'form',
          },
        }),
      routeTo: z
        .preprocess(
          (val) => (val === undefined || Array.isArray(val) ? val : [val]),
          z.array(z.string()),
        )
        .exactOptional()
        .openapi({
          param: {
            description:
              'A comma speparated list of receiver names. Limit the list of possible receivers to these receivers.',
            example: 'fl-phd.elr,fl-phd.download',
            in: 'query',
            name: 'routeTo',
            required: false,
            schema: { items: { type: 'string' }, type: 'array' },
          },
        }),
    }),
    body: {
      description: 'The public health information being routed',
      content: { 'text/csv': { schema: z.string(), example: 'header1, header2\nvalue1, value2' } },
      required: true,
    },
  },
  responses: {
    200: { description: 'OK', content: { 'application/json': { schema: ReportSchema } } },
    201: {
      description: 'Created. A report was created, but items may have been rejected.',
      content: { 'application/json': { schema: ReportSchema } },
    },
    400: {
      description: 'Invalid request. No report created.',
      content: { 'application/json': { schema: ReportSchema } },
    },
    500: { description: 'Internal Server Error' },
  },
  security: [{ ApiKeyAuth: [] }],
})

