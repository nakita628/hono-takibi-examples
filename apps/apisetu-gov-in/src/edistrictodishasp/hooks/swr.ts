export function getShcerKey() {
  return ['shcer'] as const
}

export function getPostEgcerCertificateKey() {
  return ['egcer', '/egcer/certificate', 'POST'] as const
}

export function usePostEgcerCertificate<TError = unknown>(options?: {
  mutation?: SWRMutationConfiguration<
    Awaited<
      ReturnType<typeof parseResponse<Awaited<ReturnType<typeof client.egcer.certificate.$post>>>>
    >,
    TError,
    Key,
    InferRequestType<typeof client.egcer.certificate.$post>
  > & { swrKey?: Key; throwOnError?: boolean }
  options?: ClientRequestOptions
}) {
  const { mutation: mutationOptions, options: clientOptions } = options ?? {}
  const { swrKey: customKey, ...restMutationOptions } = mutationOptions ?? {}
  const swrKey = customKey ?? getPostEgcerCertificateKey()
  return {
    swrKey,
    ...useSWRMutation(
      swrKey,
      async (_: Key, { arg }: { arg: InferRequestType<typeof client.egcer.certificate.$post> }) =>
        parseResponse(client.egcer.certificate.$post(arg, clientOptions)),
      restMutationOptions,
    ),
  }
}

