const ACHAccountIdentifierSchema = z
  .object({
    accountLastDigits: z
      .string()
      .exactOptional()
      .openapi({
        description:
          'The last digits of the account number. If the accountNumber is tokenized, this field contains the last digits of the non-tokenized account number. This helps users verify the account without seeing the full number.',
      }),
    accountNumber: z.string().openapi({ description: 'The account number of the bank account.' }),
    isTokenized: z
      .boolean()
      .exactOptional()
      .openapi({
        description:
          "Indicates whether the account number is tokenized. A tokenized account number is a unique ID generated by a bank to protect the user's actual account number.",
      }),
    routingNumber: z
      .string()
      .openapi({
        description:
          'The [routing number](https://en.wikipedia.org/wiki/ABA_routing_transit_number), without separators or whitespace.',
      }),
  })
  .openapi({ required: ['accountNumber', 'routingNumber'] })
  .openapi('ACHAccountIdentifier')

