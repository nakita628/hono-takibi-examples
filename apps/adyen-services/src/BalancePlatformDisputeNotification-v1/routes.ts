import { createRoute, z } from '@hono/zod-openapi'

const AmountSchema = z
  .strictObject({
    currency: z
      .string()
      .length(3)
      .openapi({
        description:
          'The three-character [ISO currency code](https://docs.adyen.com/development-resources/currency-codes#currency-codes) of the amount.',
      }),
    value: z
      .preprocess(
        (val) =>
          typeof val === 'number' && Number.isSafeInteger(val)
            ? BigInt(val)
            : typeof val === 'string' && /^-?\d+$/.test(val)
              ? BigInt(val)
              : val,
        z.int64(),
      )
      .openapi({
        type: 'integer',
        format: 'int64',
        description:
          'The numeric value of the amount, in [minor units](https://docs.adyen.com/development-resources/currency-codes#minor-units).',
      }),
  })
  .openapi({ required: ['currency', 'value'] })
  .openapi('Amount')

const BalancePlatformNotificationResponseSchema = z
  .strictObject({
    notificationResponse: z
      .string()
      .exactOptional()
      .openapi({
        description:
          'Respond with any **2xx** HTTP status code to [accept the webhook](https://docs.adyen.com/development-resources/webhooks/#accept-webhooks).',
      }),
  })
  .openapi({ required: [] })
  .openapi('BalancePlatformNotificationResponse')

const DisputeEventNotificationSchema = z
  .strictObject({
    arn: z
      .string()
      .exactOptional()
      .openapi({
        description:
          'The unique Acquirer Reference Number (arn) generated by the card scheme for each capture. You can use the arn to trace the transaction through its lifecycle.',
      }),
    balancePlatform: z
      .string()
      .exactOptional()
      .openapi({ description: 'The unique identifier of the balance platform.' }),
    creationDate: z.iso
      .datetime({ offset: true })
      .exactOptional()
      .openapi({
        description:
          'The date and time when the event was triggered, in ISO 8601 extended format. For example, **2025-03-19T10:15:30+01:00**.',
      }),
    description: z
      .string()
      .exactOptional()
      .openapi({ description: 'Contains information about the dispute.' }),
    disputedAmount: AmountSchema.exactOptional().openapi({
      description:
        'The amount for which the transaction is being disputed. The disputed amount cannot be greater than the transaction amount. If an amount was not provided, the entire transaction amount is disputed.',
    }),
    id: z.string().exactOptional().openapi({ description: 'The ID of the resource.' }),
    status: z
      .string()
      .exactOptional()
      .openapi({ description: 'The current status of the dispute.' }),
    statusDetail: z
      .string()
      .exactOptional()
      .openapi({
        description: 'Additional information about the status of the dispute, when available.',
      }),
    transactionId: z
      .string()
      .exactOptional()
      .openapi({
        description: 'The unique reference of the transaction for which the dispute is requested.',
      }),
    type: z
      .enum(['fraud', 'notDelivered', 'duplicate', 'notAsDescribed', 'cancelled', 'other'])
      .exactOptional()
      .openapi({ description: 'The type of dispute raised for the transaction.' }),
  })
  .openapi({ required: [] })
  .openapi('DisputeEventNotification')

const DisputeNotificationRequestSchema = z
  .strictObject({
    data: DisputeEventNotificationSchema.openapi({ description: 'Contains event details.' }),
    type: z
      .enum(['balancePlatform.dispute.created', 'balancePlatform.dispute.updated'])
      .openapi({ description: 'Type of webhook.' }),
  })
  .openapi({ required: ['data', 'type'] })
  .openapi('DisputeNotificationRequest')

const BasicAuthSecurityScheme = { type: 'http', scheme: 'basic' }

export const balancePlatformDisputeCreatedPostWebhook = {
  method: 'post',
  path: '/balancePlatform.dispute.created',
  tags: ['General'],
  summary: 'Dispute created',
  description:
    'Adyen sends this webhook when a dispute is created. This webhook only informs your server of requests. ',
  operationId: 'post-balancePlatform.dispute.created',
  request: {
    body: { content: { 'application/json': { schema: DisputeNotificationRequestSchema } } },
  },
  responses: {
    200: {
      description: 'OK - the request has succeeded.',
      content: { 'application/json': { schema: BalancePlatformNotificationResponseSchema } },
    },
  },
  security: [{ BasicAuth: [] }],
}

export const balancePlatformDisputeUpdatedPostWebhook = {
  method: 'post',
  path: '/balancePlatform.dispute.updated',
  tags: ['General'],
  summary: 'Dispute updated',
  description:
    'Adyen sends this webhook when a dispute is updated. This webhook only informs your server of requests. ',
  operationId: 'post-balancePlatform.dispute.updated',
  request: {
    body: { content: { 'application/json': { schema: DisputeNotificationRequestSchema } } },
  },
  responses: {
    200: {
      description: 'OK - the request has succeeded.',
      content: { 'application/json': { schema: BalancePlatformNotificationResponseSchema } },
    },
  },
  security: [{ BasicAuth: [] }],
}
