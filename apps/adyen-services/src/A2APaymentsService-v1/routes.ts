import { createRoute, z } from '@hono/zod-openapi'

const AccountHolderSchema = z
  .object({
    fullName: z
      .string()
      .min(1)
      .openapi({ description: 'Full name of the account holder.', example: 'John Doe' }),
  })
  .openapi({ required: ['fullName'] })
  .openapi('AccountHolder')

const AccountIdentificationSchema = z
  .object({ type: z.string() })
  .openapi({
    discriminator: {
      propertyName: 'type',
      mapping: { iban: '#/components/schemas/IbanAccountIdentification' },
    },
    required: ['type'],
  })
  .openapi('AccountIdentification')

const AmountSchema = z
  .object({
    currency: z
      .string()
      .min(1)
      .openapi({
        description:
          'The three-character [ISO 4217 currency code](https://docs.adyen.com/development-resources/currency-codes#currency-codes).',
        example: 'EUR',
      }),
    value: z
      .preprocess(
        (val) =>
          typeof val === 'number' && Number.isSafeInteger(val)
            ? BigInt(val)
            : typeof val === 'string' && /^-?\d+$/.test(val)
              ? BigInt(val)
              : val,
        z.int64(),
      )
      .openapi({
        type: 'integer',
        format: 'int64',
        description:
          'The amount of the transaction in [minor units](https://docs.adyen.com/development-resources/currency-codes#minor-units) (cents).',
        example: 499,
      }),
  })
  .openapi({ required: ['currency', 'value'] })
  .openapi('Amount')

